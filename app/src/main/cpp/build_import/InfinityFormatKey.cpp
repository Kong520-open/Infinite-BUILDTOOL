#include "InfinityFormatKey.h"

#include <array>
#include <cstddef>
#include <cstdint>

namespace build_import {

const InfinityCryptoCodec::Key& infinityFormatKeyV1() {
    static const InfinityCryptoCodec::Key key = [] {
        constexpr std::array<uint8_t, InfinityCryptoCodec::kKeySize> mask{{
            0xd4, 0xf9, 0x67, 0x09, 0xf9, 0x7e, 0xf4, 0x68,
            0x0e, 0x57, 0x59, 0xf6, 0xb4, 0x3f, 0x54, 0x2d,
            0x1e, 0x28, 0xaf, 0x8d, 0xd4, 0xde, 0xe4, 0x7e,
            0x85, 0x95, 0x84, 0x10, 0x71, 0xf7, 0xe1, 0xe2,
        }};
        constexpr std::array<uint8_t, InfinityCryptoCodec::kKeySize> masked{{
            0x87, 0x75, 0x3a, 0xde, 0xee, 0xeb, 0x61, 0x71,
            0xac, 0x94, 0xc2, 0x0d, 0x5a, 0xab, 0xae, 0x8d,
            0x72, 0x40, 0x63, 0x20, 0xd3, 0x69, 0x3f, 0xca,
            0xd7, 0x22, 0x08, 0xa9, 0xf9, 0x86, 0x62, 0xb9,
        }};
        InfinityCryptoCodec::Key result{};
        for (size_t index = 0; index < result.size(); ++index) {
            result[index] = static_cast<uint8_t>(mask[index] ^ masked[index]);
        }
        return result;
    }();
    return key;
}

}  // namespace build_import
